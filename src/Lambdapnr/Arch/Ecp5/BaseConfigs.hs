import Data.Map.Strict (Map)
import qualified Data.Map.Strict as M
import Data.Text (Text)

import Lambdapnr.Arch.Ecp5.Config

-- | One base-config entry (generated data).
data Entry = E Text Text | A Text Text | U Int Int

-- | The empty base configuration of a device (by chip name).
configEmpty :: Text -> Map Text TileConfig
configEmpty name = case name of
    "LFE5U-25F" -> base_lfe5u_25f
    "LFE5U-45F" -> base_lfe5u_45f
    "LFE5U-85F" -> base_lfe5u_85f
    "LFE5UM-25F" -> base_lfe5um_25f
    "LFE5UM-45F" -> base_lfe5um_45f
    "LFE5UM5G-25F" -> base_lfe5um5g_25f
    "LFE5UM5G-45F" -> base_lfe5um5g_45f
    "LFE5UM5G-85F" -> base_lfe5um5g_85f
    "LFE5UM-85F" -> base_lfe5um_85f
    _ -> error ("lambdapnr: unknown device " ++ show name)


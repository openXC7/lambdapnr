{- | The ECP5 empty base configurations, ported mechanically from
@ecp5\/baseconfigs.cc@ (the @BaseConfigs::config_empty_*@ functions).
Each device's default tile settings (CIB mux enums, fixed arcs and
unknown bits) are the starting point @--textcfg@ builds on; the bitgen
adds routing arcs and cell settings on top. -}
